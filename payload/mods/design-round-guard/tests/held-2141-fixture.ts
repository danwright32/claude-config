  "  }",
  "  if (why) return { unresolved: why, commands }",
  "  let text = word",
  "  for (const p of [...parts].reverse()) text = text.slice(0, p.pos) + p.text + text.slice(p.pos + p.len)",
  "  return { text, commands }",
