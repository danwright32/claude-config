// area-check-fixture.ts: writes the replay fixture the area check's replay test reads
// (payload/mods/area-check/tests/replay-fixture/), for tools/area-check-replay.ts --fixture (#2097).
//
// The fixture is a folder: index.ts, which puts the month back together, and parts beside it holding
// the rows, ONE RECORD PER LINE (a path, an issue, a tracked file, a day's growth for one file, a
// session). It was once one module of three lines, two of them 190 KB and 31 KB long, so a month
// measured again was a diff of every byte of both months that no reviewer could read, and it put
// #1509's branch past the lessons review's 300 KB limit with one file over the 292 KB a group of
// files can hold. Row per line, a month measured again reads as the rows that changed.
//
// PART_BYTES caps each part. Measuring a new month can rewrite every row, so a part's diff is at most
// its old text plus its new, about 200 KB plus context at this size, which stays under what one group
// of the review holds (PR_REVIEW_MAX_BYTES less the file list and history) however the month moves. A
// row bigger than a part on its own still goes in a part of its own, since a row is never split.
//
// What is written is read back before it replaces anything: the folder is built beside the target,
// imported, and must decode to exactly the input and summary measured, key order included, or nothing
// is replaced and the writer throws (L5). A folder written again is replaced whole, so no part from an
// earlier, longer month is left behind for index.ts to miss or a reader to mistake for data.
import { existsSync, mkdirSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { basename, dirname, join } from 'node:path'
import { pathToFileURL } from 'node:url'
import type { ReplayInput, ReplaySummary } from '../payload/mods/area-check/hooks/rules.ts'

export const PART_BYTES = 100 * 1024

export type PackedSession = { id: string; day: string; own: number[]; files: number[] }
export type PackedInput = Omit<ReplayInput, 'sessions'> & { sessions: PackedSession[] }
export type Fixture = {
  repo: string
  head: string
  rule: number
  /** The day it was measured, YYYY-MM-DD. */
  measuredOn: string
  /** The window replayed, in days. */
  days: number
  /** Every judged file a session edits, sorted; a session names its files by place in this list. */
  paths: string[]
  input: PackedInput
  summary: ReplaySummary
}

type Table = { name: string; about: string; type: string; rows: string[]; imports?: string }

const partFile = (t: Table, rows: string[]) =>
  `// Generated by tools/area-check-replay.ts for index.ts beside it: ${t.about}, one per line.\n` +
  `// Measure again rather than edit (L48).\n` +
  (t.imports ? `${t.imports}\n` : '') +
  `export const ROWS: ${t.type}[] = [\n` +
  rows.map(r => `${r},\n`).join('') +
  `]\n`

/** The rows of a table dealt into parts of at most partBytes each, a row never split. */
const deal = (t: Table, partBytes: number): string[][] => {
  const parts: string[][] = []
  let cur: string[] = []
  let size = Buffer.byteLength(partFile(t, []))
  for (const r of t.rows) {
    const add = Buffer.byteLength(r) + 2
    if (cur.length && size + add > partBytes) {
      parts.push(cur)
      cur = []
      size = Buffer.byteLength(partFile(t, []))
    }
    cur.push(r)
    size += add
  }
  parts.push(cur)
  return parts
}

/** The files of the fixture folder, by name, in the order they are written. */
export const fixtureFiles = (fx: Fixture, partBytes: number = PART_BYTES): Map<string, string> => {
  const j = (x: unknown) => JSON.stringify(x)
  const dayNames = Object.keys(fx.input.days)
  const growthRows: string[] = []
  for (const d of dayNames) {
    const facts = fx.input.days[d] as ReplayInput['days'][string]
    for (const [p, g] of Object.entries(facts.growth)) growthRows.push(j([d, p, g.net, g.fixes, facts.sizes[p]]))
  }
  const tables: Table[] = [
    { name: 'paths', about: 'the judged files the sessions edit, sorted, each session naming its files by place in this list', type: 'string', rows: fx.paths.map(j) },
    { name: 'issues', about: 'the open issues that name a path: number, structural labels, priority, the paths named', type: 'CachedIssue', rows: fx.input.issues.map(j), imports: "import type { CachedIssue } from '../../hooks/rules.ts'" },
    { name: 'tracked', about: 'the tracked files sharing a basename with a path an issue names or a session edits', type: 'string', rows: fx.input.tracked.map(j) },
    { name: 'growth', about: "each day's rankable files: day, path, net lines grown and fix commits over the 90 days before it, its lines", type: '[string, string, number, number, number]', rows: growthRows },
    { name: 'sessions', about: 'the sessions, each a commit: id, day, the issues its subject names, its judged files as places in PATHS', type: '{ id: string; day: string; own: number[]; files: number[] }', rows: fx.input.sessions.map(j) },
  ]
  const files = new Map<string, string>()
  const imports: string[] = []
  const spread: Record<string, string> = {}
  for (const t of tables) {
    const names: string[] = []
    deal(t, partBytes).forEach((rows, i) => {
      const file = `${t.name}-${i + 1}.ts`
      const local = `${t.name}${i + 1}`
      files.set(file, partFile(t, rows))
      imports.push(`import { ROWS as ${local} } from './${file}'`)
      names.push(`...${local}`)
    })
    spread[t.name] = `[${names.join(', ')}]`
  }
  const summary = Object.entries(fx.summary).map(([k, v]) => `    ${j(k)}: ${j(v)},\n`).join('')
  files.set(
    'index.ts',
    `// Measured by tools/area-check-replay.ts from ${fx.repo} on ${fx.measuredOn}: ${fx.days} days to ${fx.head.slice(0, 10)}, rules v${fx.rule}.\n` +
      `// Generated; measure again rather than edit (L48). The rows are in the parts beside this file, one\n` +
      `// per line (#2097), and each session's files are places in PATHS.\n` +
      `import type { ReplayInput, ReplaySummary } from '../../hooks/rules.ts'\n` +
      imports.join('\n') + '\n\n' +
      `export const PATHS: string[] = ${spread.paths}\n\n` +
      `// Every day of the window in order, so a day with no rankable file is still a day.\n` +
      `const DAYS: string[] = [\n` + dayNames.map(d => `  ${j(d)},\n`).join('') + `]\n` +
      `const days: ReplayInput['days'] = {}\n` +
      `for (const d of DAYS) days[d] = { growth: {}, sizes: {} }\n` +
      `for (const [d, p, net, fixes, lines] of ${spread.growth}) {\n` +
      `  const day = days[d] ?? (days[d] = { growth: {}, sizes: {} })\n` +
      `  day.growth[p] = { net, fixes }\n` +
      `  day.sizes[p] = lines\n` +
      `}\n\n` +
      `export const MEASURED: { repo: string; head: string; rule: number; input: Omit<ReplayInput, 'sessions'> & { sessions: { id: string; day: string; own: number[]; files: number[] }[] }; summary: ReplaySummary } = {\n` +
      `  repo: ${j(fx.repo)},\n` +
      `  head: ${j(fx.head)},\n` +
      `  rule: ${j(fx.rule)},\n` +
      `  input: { issues: ${spread.issues}, tracked: ${spread.tracked}, days, sessions: ${spread.sessions} },\n` +
      `  summary: {\n${summary}  },\n` +
      `}\n`,
  )
  return files
}

/** What a fixture decodes to, key order kept: what the folder must read back as. */
const decoded = (paths: unknown, measured: { repo: unknown; head: unknown; rule: unknown; input: unknown; summary: unknown }) =>
  JSON.stringify({ paths, repo: measured.repo, head: measured.head, rule: measured.rule, input: measured.input, summary: measured.summary })

/**
 * Writes the fixture folder at dir, replacing any folder there only once the new one has been read
 * back and decodes to exactly what was measured. Throws, with nothing replaced, when it cannot.
 */
export const writeFixture = async (dir: string, fx: Fixture, partBytes: number = PART_BYTES): Promise<void> => {
  const tmp = join(dirname(dir), `.${basename(dir)}.writing-${process.pid}`)
  rmSync(tmp, { recursive: true, force: true })
  mkdirSync(tmp)
  try {
    for (const [name, text] of fixtureFiles(fx, partBytes)) writeFileSync(join(tmp, name), text)
    const back = (await import(pathToFileURL(join(tmp, 'index.ts')).href)) as { PATHS: unknown; MEASURED: Parameters<typeof decoded>[1] }
    if (decoded(back.PATHS, back.MEASURED) !== decoded(fx.paths, fx))
      throw new Error('the folder written does not read back as the month measured')
    const old = `${tmp}-old`
    const had = existsSync(dir)
    if (had) renameSync(dir, old)
    try {
      renameSync(tmp, dir)
    } catch (err) {
      if (had) renameSync(old, dir)
      throw err
    }
    rmSync(old, { recursive: true, force: true })
  } finally {
    rmSync(tmp, { recursive: true, force: true })
  }
}
